export const dictionaries: Record<Lang, Record<Key, string>> = { ar, fr }

export interface I18n {
  lang: Lang
  t: (key: Key, vars?: Record<string, string | number>) => string
  reason: (code: string) => string
  alertTitle: (type: string) => string
}

export function makeI18n(lang: Lang): I18n {
  const d = dictionaries[lang]
  return {
    lang,
    t: (key, vars) => Object.entries(vars ?? {}).reduce((s, [k, v]) => s.replace(`{${k}}`, String(v)), d[key] ?? key),
    reason: (code) => reasons[lang][code] ?? code,
    alertTitle: (type) => alertTitles[type]?.[lang === 'ar' ? 0 : 1] ?? type,
  }
}

export const I18nContext = createContext<I18n>(makeI18n('ar'))
export const useI18n = () => useContext(I18nContext)
